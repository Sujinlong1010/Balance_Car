/**
* @brief Function implementing the BalanceTask thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_StartBalanceTask */
void StartBalanceTask(void *argument)
{
  /* USER CODE BEGIN StartBalanceTask */
  /* Fixed 200 Hz control loop (5 ms). vTaskDelayUntil keeps the period
   * steady instead of accumulating osDelay drift. This task has higher
   * priority than defaultTask so the loop is not blocked by OLED refresh. */
  TickType_t xLastWake = xTaskGetTickCount();
  const TickType_t xPeriod = pdMS_TO_TICKS(5U);

  for(;;)
  {
    App_Balance_Tick(HAL_GetTick());
    vTaskDelayUntil(&xLastWake, xPeriod);
  }
  /* USER CODE END StartBalanceTask */
}

